#!/usr/bin/env python3
"""Uncertainty trigger feasibility: does the entropy of a turn (logged by the in-process provider
for every generated token) predict that the turn's tool call fails, or that the task fails?

Joins each native run's per-request metrics (entropy) with its pi session (tool results) in order,
and reports ROC AUC of several entropy statistics. Writes results/uncertainty.md.

Needs results/raw/<arm>/ (tar -xJf results/raw-artifacts.tar.xz -C results/raw).
"""
import glob, json, os

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(REPO, "results", "raw")


def auc(pos, neg):
    if not pos or not neg:
        return float("nan")
    s = 0.0
    for p in pos:
        for n in neg:
            s += 1.0 if p > n else 0.5 if p == n else 0.0
    return s / (len(pos) * len(neg))


def turns_of(session_dir):
    """Assistant turns in order, each with whether any of its tool results was an error."""
    out = []
    for f in glob.glob(os.path.join(session_dir, "*.jsonl")):
        for line in open(f):
            m = (json.loads(line).get("message") or {})
            if m.get("role") == "assistant":
                out.append({"calls": sum(1 for c in m.get("content") or [] if isinstance(c, dict) and c.get("type") == "toolCall"), "error": False})
            elif m.get("role") == "toolResult" and out:
                out[-1]["error"] |= bool(m.get("isError"))
    return out


def main():
    turn_rows, task_rows = [], []
    for arm_file in glob.glob(os.path.join(RAW, "native*.jsonl")):
        arm = os.path.basename(arm_file)[:-6]
        for line in open(arm_file):
            r = json.loads(line)
            name = f"{r['task']}-r{r['round']}"
            mfile = os.path.join(RAW, arm, name + ".metrics.jsonl")
            sdir = os.path.join(os.path.expanduser("~/.cache/pi-extras/llama-native/sessions"), arm, name + ".session")
            if not os.path.exists(mfile):
                continue
            reqs = [json.loads(l) for l in open(mfile)]
            reqs = [q for q in reqs if q.get("kind", "chat") == "chat" and q.get("timings")]
            turns = turns_of(sdir)
            ents = []
            for q, t in zip(reqs, turns):
                e = (q["timings"].get("entropy") or {})
                act, al = e.get("act") or {}, e.get("all") or {}
                if not al:
                    continue
                row = {"arm": arm, "task": name, "err": t["error"], "calls": t["calls"],
                       "act_mean": act.get("mean"), "act_max": act.get("max"), "act_high": act.get("frac_high"),
                       "all_mean": al.get("mean"), "all_p90": al.get("p90")}
                turn_rows.append(row)
                ents.append(row)
            if ents:
                task_rows.append({"arm": arm, "task": name, "passed": r["passed"],
                                  "max_act_mean": max((x["act_mean"] or 0) for x in ents),
                                  "mean_all": sum(x["all_mean"] or 0 for x in ents) / len(ents)})
    out = ["# Uncertainty (entropy) as a trigger (generated by bench/uncertainty.py)\n",
           f"{len(turn_rows)} turns with tool calls or answers from {len(task_rows)} in-process runs.\n",
           "| predictor | target | positives | negatives | ROC AUC |", "|---|---|---|---|---|"]
    with_calls = [x for x in turn_rows if x["calls"] > 0]
    for k in ("act_mean", "act_max", "act_high", "all_mean", "all_p90"):
        pos = [x[k] for x in with_calls if x["err"] and x[k] is not None]
        neg = [x[k] for x in with_calls if not x["err"] and x[k] is not None]
        out.append(f"| turn {k} | tool result is an error | {len(pos)} | {len(neg)} | {auc(pos, neg):.2f} |")
    for k in ("max_act_mean", "mean_all"):
        pos = [x[k] for x in task_rows if not x["passed"]]
        neg = [x[k] for x in task_rows if x["passed"]]
        out.append(f"| task {k} | task fails hidden tests | {len(pos)} | {len(neg)} | {auc(pos, neg):.2f} |")
    if with_calls:
        e = [x["act_mean"] for x in with_calls if x["act_mean"] is not None]
        e.sort()
        if e:
            out.append(f"\nPost-reasoning entropy per turn (nats): median {e[len(e)//2]:.3f}, p90 {e[int(0.9*(len(e)-1))]:.3f}, max {e[-1]:.3f}.")
    open(os.path.join(REPO, "results", "uncertainty.md"), "w").write("\n".join(out) + "\n")
    print("\n".join(out))


if __name__ == "__main__":
    main()
