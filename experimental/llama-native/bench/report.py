#!/usr/bin/env python3
"""Aggregate results/raw into results/summary.md (tables used by RESULTS.md)."""
import glob, json, os, statistics as st, sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RAW = os.path.join(REPO, "results", "raw")
ORDER = ["http", "native", "native+server-cache", "native+no-spec", "native+no-grammar", "http+prune", "native+prune",
         "http+done-check", "native+done-check", "native+helper-decide", "http+think-route", "native+think-route"]


def mean(xs):
    xs = [x for x in xs if x is not None]
    return st.mean(xs) if xs else float("nan")


def med(xs):
    xs = [x for x in xs if x is not None]
    return st.median(xs) if xs else float("nan")


def load_arm(path):
    return [json.loads(l) for l in open(path)]


def arm_row(name, rows):
    n = len(rows)
    passed = sum(r["passed"] for r in rows)
    first_ttft = [r["ttft_ms"][0] for r in rows if r["ttft_ms"]]
    later_ttft = [t for r in rows for t in r["ttft_ms"][1:]]
    drafted = sum(r["drafted"] for r in rows)
    acc = sum(r["draft_accepted"] for r in rows)
    gen_ms = sum(r["gen_ms"] for r in rows)
    gen = sum(r["generated"] for r in rows)
    dec = [d for r in rows for d in r.get("decide", []) if not d.get("error")]
    return {
        "arm": name, "runs": n, "passed": passed, "pass_rate": passed / n if n else 0,
        "wall_s": mean([r["wall_minus_load_s"] for r in rows]),
        "load_s": mean([r["load_s"] for r in rows]),
        "requests": mean([r["requests"] for r in rows]),
        "ttft_first_ms": med(first_ttft), "ttft_later_ms": med(later_ttft),
        "prompt_processed": mean([r["prompt_processed"] for r in rows]),
        "prompt_reused": mean([r["prompt_reused"] for r in rows]),
        "refed": mean([r.get("refed", 0) for r in rows]),
        "generated": mean([r["generated"] for r in rows]),
        "decode_tps": gen / (gen_ms / 1000) if gen_ms else float("nan"),
        "accept": acc / drafted if drafted else float("nan"),
        "tool_calls": mean([r["tool_calls"] for r in rows]),
        "tool_errors": sum(r["tool_errors"] for r in rows),
        "malformed": sum(r["malformed_calls"] for r in rows) + sum(r.get("parse_errors", 0) for r in rows),
        "provider_errors": sum(r.get("provider_errors", 0) for r in rows),
        "timeouts": sum(1 for r in rows if r["timed_out"]),
        "vram0": max((r["vram_peak_mib"].get("gpu0", 0) for r in rows), default=0),
        "vram1": max((r["vram_peak_mib"].get("gpu1", 0) for r in rows), default=0),
        "max_prompt": max((r["max_prompt"] for r in rows), default=0),
        "decisions": len(dec), "decide_ms": med([d.get("timings", {}).get("total_ms") for d in dec]),
        "nudges": sum(1 for d in dec if d.get("nudge")), "skips": sum(1 for d in dec if d.get("skip_thinking")),
        "prunes": sum(len(r.get("prune", [])) for r in rows),
    }


def fmt(v, nd=1):
    if isinstance(v, float):
        return "–" if v != v else f"{v:.{nd}f}"
    return str(v)


def main():
    arms = {}
    for p in glob.glob(os.path.join(RAW, "*.jsonl")):
        name = os.path.basename(p)[:-6]
        if name.startswith("trial"):
            continue
        arms[name] = load_arm(p)
    names = [a for a in ORDER if a in arms] + sorted(a for a in arms if a not in ORDER)
    rows = [arm_row(a, arms[a]) for a in names]
    out = ["# Benchmark summary (generated by bench/report.py)\n"]
    out.append("Wall time excludes the in-process model load (reported separately). TTFT is measured by the client "
               "side of each path (logging proxy / extension), first request of a task vs. later ones (medians).\n")
    out.append("| arm | pass | wall s | load s | req | TTFT 1st ms | TTFT later ms | prompt proc | prompt reused | re-fed | gen | decode tok/s | draft acc | tool calls | tool err | malformed | timeouts | VRAM0/1 MiB |")
    out.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        out.append(f"| {r['arm']} | {r['passed']}/{r['runs']} | {fmt(r['wall_s'])} | {fmt(r['load_s'])} | {fmt(r['requests'])} | "
                   f"{fmt(r['ttft_first_ms'],0)} | {fmt(r['ttft_later_ms'],0)} | {fmt(r['prompt_processed'],0)} | {fmt(r['prompt_reused'],0)} | "
                   f"{fmt(r['refed'],0)} | {fmt(r['generated'],0)} | {fmt(r['decode_tps'])} | {fmt(r['accept'],2)} | {fmt(r['tool_calls'])} | "
                   f"{r['tool_errors']} | {r['malformed']} | {r['timeouts']} | {r['vram0']}/{r['vram1']} |")
    out.append("\nPer-task means are over all runs of the arm (prompt/gen columns are tokens per task).\n")
    dec = [r for r in rows if r["decisions"] or r["prunes"]]
    if dec:
        out.append("## Decisions and context edits\n")
        out.append("| arm | decisions | median decision ms | nudges | thinking skipped | prune batches |")
        out.append("|---|---|---|---|---|---|")
        for r in dec:
            out.append(f"| {r['arm']} | {r['decisions']} | {fmt(r['decide_ms'],0)} | {r['nudges']} | {r['skips']} | {r['prunes']} |")
    # per task pass table
    tasks = sorted({r["task"] for a in names for r in arms[a]})
    out.append("\n## Passes per task\n")
    out.append("| arm | " + " | ".join(tasks) + " |")
    out.append("|---|" + "---|" * len(tasks))
    for a in names:
        cells = []
        for t in tasks:
            rs = [r for r in arms[a] if r["task"] == t]
            cells.append(f"{sum(r['passed'] for r in rs)}/{len(rs)}" if rs else "")
        out.append(f"| {a} | " + " | ".join(cells) + " |")
    out.append("\n## Mean wall time per task (s, excluding model load)\n")
    out.append("| arm | " + " | ".join(tasks) + " |")
    out.append("|---|" + "---|" * len(tasks))
    for a in names:
        cells = []
        for t in tasks:
            rs = [r["wall_minus_load_s"] for r in arms[a] if r["task"] == t]
            cells.append(fmt(mean(rs), 0) if rs else "")
        out.append(f"| {a} | " + " | ".join(cells) + " |")
    # long-context scenario
    lc = sorted(glob.glob(os.path.join(RAW, "longctx", "*.json")))
    if lc:
        out.append("\n## Long-context session (5 prompts + /compact, bench/longctx.py)\n")
        out.append("| run | total s | prompt steps s | compact s | after-compact prompt s | tokens before compact | prompt proc | re-fed | max prompt | prunes | hidden tests |")
        out.append("|---|---|---|---|---|---|---|---|---|---|---|")
        for p in lc:
            d = json.load(open(p))
            m = p[:-5] + ".metrics.jsonl"
            proc = refed = mx = prunes = 0
            if os.path.exists(m):
                for l in open(m):
                    r = json.loads(l)
                    if r.get("kind") == "prune":
                        prunes += 1
                    t = r.get("timings")
                    if r.get("kind", "chat") != "chat" or not t:
                        continue
                    if "prompt_decoded" in t:
                        proc += t["prompt_decoded"]; refed += t.get("refed", 0); mx = max(mx, t["prompt_n"])
                    else:
                        proc += t["prompt_n"]; mx = max(mx, t["prompt_n"] + t["cache_n"])
            steps = d["steps"]
            comp = next((s for s in steps if s["kind"] == "compact"), {})
            prompts = [s["s"] for s in steps if s["kind"] == "prompt"]
            out.append(f"| {os.path.basename(p)[:-5]} | {d['total_s']} | {' / '.join(str(x) for x in prompts[:-1])} | "
                       f"{comp.get('s', '')} | {prompts[-1] if prompts else ''} | {comp.get('tokensBefore', '')} | {proc} | {refed} | {mx} | {prunes} | "
                       f"{'pass' if d['hidden_passed'] else 'fail'} |")
    open(os.path.join(REPO, "results", "summary.md"), "w").write("\n".join(out) + "\n")
    json.dump(rows, open(os.path.join(REPO, "results", "summary.json"), "w"), indent=1)
    print("\n".join(out))


if __name__ == "__main__":
    main()
