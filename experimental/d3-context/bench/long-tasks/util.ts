// Shared writing helpers of the long-ticket generator. A ticket folder is
//   <task>/issue.md  <task>/repo/**  <task>/hidden.test.ts  [<task>/ref/**]
// and the shared bench (bench/lib/tickets.ts) seeds repo/, runs pi, and grades with hidden.test.ts.
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

export interface Writer {
	(rel: string, text: string): void;
	/** The absolute path of a ticket file: the generator reads back what it wrote. */
	path(rel: string): string;
}

export function makeWriter(root: string, task: string): Writer {
	const w = ((rel: string, text: string) => {
		const p = join(root, task, rel);
		mkdirSync(dirname(p), { recursive: true });
		writeFileSync(p, text);
	}) as Writer;
	w.path = (rel: string) => join(root, task, rel);
	return w;
}

export const range = (n: number, f: (i: number) => string) => Array.from({ length: n }, (_, i) => f(i + 1)).join("\n");
export const lines = (xs: string[]) => xs.join("\n") + "\n";
export const pad = (i: number, n = 3) => String(i).padStart(n, "0");
export const money = (cents: number) => (cents / 100).toFixed(2);
export const jsonl = (xs: any[]) => xs.map((x) => JSON.stringify(x)).join("\n") + "\n";

/** The last instruction of every long ticket: cite the evidence, so the run can be scored on it. */
export const CITE =
	"Write `notes.md` in the repository root (overwrite it). Answer each question, and for every fact you use cite it as `file:line` on a line of its own. A fact without a citation counts as a guess.";

/** The outcome tests: the answer file must name the right facts and cite its evidence. */
export function outcomeTest(expected: object, checks: string): string {
	return `// Generated by gen-long-tasks.ts: do not edit.
import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { test } from "node:test";

const EXPECTED = ${JSON.stringify(expected, null, 1)};
const notes = existsSync("notes.md") ? readFileSync("notes.md", "utf8") : "";
const numbers = (re: RegExp) => (notes.match(re) ?? []).map(Number);
const says = (s: string) => notes.includes(s);

test("the answer file exists", () => {
	assert.ok(notes.trim().length > 0, "notes.md is missing: the facts were never written down");
});

${checks}

test("every fact is cited as file:line", () => {
	const cited = (notes.match(/[\\w./-]+:\\d+/g) ?? []).length;
	assert.ok(cited >= 8, \`only \${cited} citations in notes.md\`);
});
`;
}

export interface Task {
	name: string;
	/** The ticket's questions, as the agent sees them. */
	questions: string[];
	/** The fixtures, the issue and the outcome test. */
	build(w: Writer): { expected: object; checks: string; ref?: Record<string, string> } | Promise<{ expected: object; checks: string; ref?: Record<string, string> }>;
}
